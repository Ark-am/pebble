#!/usr/bin/env python3
"""Writes the sound effects for the watch, and previews to listen to.

Each sound is one or two tracks of notes, played at once. A note is a MIDI
note number (0 is a rest), a waveform, a length in milliseconds and a loudness
from 1 to 127.

Run from the project directory (needs only Python):

    python3 tools/make_sounds.py [preview folder]

It writes src/c/sounds.h and, if a folder is given, a WAV file of each sound
there, plus demo.wav, which plays a whole trip through the avatars. The
watch's small speaker will sound thinner than a computer's.
"""

import math
import os
import struct
import sys
import wave

SINE, SQUARE, TRIANGLE, SAWTOOTH = range(4)
REST = 0
RATE = 16000

# A step's pitch depends on the plate: a pentatonic scale round the ring.
SCALE = [69, 72, 74, 76, 79, 81, 84, 86, 88, 91, 93, 96]


def ratchet():
    """The ring spinning up and slowing to a stop over 900 ms: ticks that
    spread out, climbing in pitch, then a note as it lands."""
    notes = []
    for i, gap in enumerate((8, 10, 12, 16, 20, 26, 34, 44, 58, 76, 100)):
        notes += [(74 + i * 2, SQUARE, 14, 90), (REST, SQUARE, gap, 0)]
    return notes + [(98, TRIANGLE, 150, 90)]


def spin_hum():
    """A hum that rises under the ratchet."""
    return [(40 + i * 3, TRIANGLE, 60, 45) for i in range(14)]


def surge():
    """The charge rushing up as the iris closes, then the low boom as the
    plates flash, dying away."""
    notes = [(40 + i * 4, SAWTOOTH, 20, 80 + i * 3) for i in range(13)]
    return notes + [(33, SAWTOOTH, 110, 127), (33, SAWTOOTH, 90, 80), (33, SAWTOOTH, 90, 50),
                    (33, SAWTOOTH, 110, 25)]


def sparks():
    """Bright notes falling as the sparks and shock rings fly out."""
    notes = [(REST, SINE, 250, 0)]
    for i, note in enumerate((96, 91, 88, 84, 79, 76, 72)):
        notes.append((note, SQUARE, 55, 70 - i * 8))
    return notes


# Each avatar's call as it arrives.
CALLS = [
    ('OCTAVO', [(52, TRIANGLE, 90, 110), (55, TRIANGLE, 90, 100), (52, TRIANGLE, 90, 90),
                (48, TRIANGLE, 180, 80)]),
    ('SPORELET', [(76, SQUARE, 60, 90), (84, SQUARE, 60, 90), (79, SQUARE, 60, 90),
                  (88, SQUARE, 140, 80)]),
    ('LUMOTH', [(88, SINE, 60, 90), (91, SINE, 60, 90), (88, SINE, 60, 90), (91, SINE, 60, 90),
                (93, SINE, 180, 80)]),
    ('HORNBACK', [(40, SAWTOOTH, 110, 120), (40, SAWTOOTH, 110, 100), (43, SAWTOOTH, 220, 110)]),
    ('WYRMLING', [(52, SAWTOOTH, 70, 100), (59, SAWTOOTH, 70, 110), (64, SAWTOOTH, 70, 120),
                  (71, SAWTOOTH, 240, 110)]),
    ('DRIFTJELLY', [(84, SINE, 90, 90), (81, SINE, 90, 85), (79, SINE, 90, 80),
                    (76, SINE, 90, 70), (74, SINE, 180, 60)]),
    ('HOOTAN', [(69, SINE, 170, 110), (REST, SINE, 90, 0), (67, SINE, 280, 100)]),
    ('COILFANG', [(96, SQUARE, 30, 60), (97, SQUARE, 30, 60)] * 6),
    ('STINGTAIL', [(76, SQUARE, 30, 100), (REST, SQUARE, 70, 0), (76, SQUARE, 30, 100),
                   (REST, SQUARE, 70, 0), (88, SQUARE, 120, 110)]),
    ('OCULON', [(72, SINE, 90, 100), (79, SINE, 90, 100), (84, SINE, 120, 100),
                (79, SINE, 90, 90), (72, SINE, 150, 80)]),
    ('SKYRAY', [(67, TRIANGLE, 80, 90), (71, TRIANGLE, 80, 95), (74, TRIANGLE, 80, 100),
                (79, TRIANGLE, 80, 105), (83, TRIANGLE, 200, 100)]),
    ('PINCERA', [(70, SQUARE, 30, 110), (REST, SQUARE, 60, 0), (70, SQUARE, 30, 110),
                 (REST, SQUARE, 60, 0), (58, SQUARE, 160, 100)]),
]

SOUNDS = [
    ('SFX_OPEN', [ratchet(), spin_hum()]),
    ('SFX_PIP_1', [[(84, SINE, 45, 80)]]),
    ('SFX_PIP_2', [[(91, SINE, 45, 90)]]),
    ('SFX_TRANSFORM', [surge(), sparks()]),
    ('SFX_BACK', [[(79, TRIANGLE, 40, 90), (72, TRIANGLE, 60, 80)]]),
    ('SFX_CLOSE', [[(84 - i * 5, SINE, 45, 100 - i * 8) for i in range(8)]]),
    ('SFX_POWER', [[(note, SQUARE, 45, 40 + i * 5) for i, note in enumerate(SCALE)],
                   [(REST, SINE, 540, 0), (60, SINE, 300, 60)]]),
    ('SFX_CHASE', [[(note, TRIANGLE, 80, 55) for note in SCALE]]),
]


def step(plate):
    return [[(SCALE[plate], SQUARE, 18, 100), (SCALE[plate] + 12, TRIANGLE, 32, 70)]]


def c_notes(name, notes):
    body = ', '.join('{ %d, %d, %d, %d, 0 }' % note for note in notes)
    return 'static const SpeakerNote %s[] = { %s };' % (name, body)


def c_sound(name, tracks):
    lines = []
    entries = []
    for i, notes in enumerate(tracks):
        track = '%s_T%d' % (name, i)
        lines.append(c_notes(track, notes))
        entries.append('{ %s, %d, NULL }' % (track, len(notes)))
    lines.append('static const SpeakerTrack %s_TRACKS[] = { %s };' % (name, ', '.join(entries)))
    lines.append('static const Sound %s = { %s_TRACKS, %d };' % (name, name, len(tracks)))
    return lines


def write_header():
    lines = [
        '// Generated by tools/make_sounds.py; do not edit.',
        '',
        '#pragma once',
        '',
        '#include <pebble.h>',
        '',
        '// One or two tracks of notes, played at once.',
        'typedef struct {',
        '  const SpeakerTrack *tracks;',
        '  uint8_t count;',
        '} Sound;',
        '',
    ]
    for name, tracks in SOUNDS:
        lines += c_sound(name, tracks)
    for plate in range(len(SCALE)):
        lines += c_sound('SFX_STEP_%d' % plate, step(plate))
    for name, notes in CALLS:
        lines += c_sound('SFX_CALL_%s' % name, [notes])
    lines += ['', '// The step for each plate, and each avatar\'s call.',
              'static const Sound *const SFX_STEPS[] = {']
    lines += ['  &SFX_STEP_%d,' % plate for plate in range(len(SCALE))]
    lines += ['};', '', 'static const Sound *const SFX_CALLS[] = {']
    lines += ['  &SFX_CALL_%s,' % name for name, _ in CALLS]
    lines += ['};', '']
    with open('src/c/sounds.h', 'w') as f:
        f.write('\n'.join(lines))


def sample(waveform, phase):
    phase %= 1.0
    if waveform == SINE:
        return math.sin(2 * math.pi * phase)
    if waveform == SQUARE:
        return 1.0 if phase < 0.5 else -1.0
    if waveform == TRIANGLE:
        return 4 * abs(phase - 0.5) - 1
    return 2 * phase - 1


def synth(tracks):
    """The tracks mixed, as a list of samples from -1 to 1."""
    length = max(sum(note[2] for note in notes) for notes in tracks)
    out = [0.0] * (length * RATE // 1000 + 1)
    for notes in tracks:
        at = 0
        for midi, waveform, ms, loudness in notes:
            count = ms * RATE // 1000
            if midi:
                frequency = 440 * 2 ** ((midi - 69) / 12)
                for i in range(count):
                    # A short fade at each end stops clicks.
                    edge = min(1.0, min(i, count - i) / 40)
                    out[at + i] += sample(waveform, frequency * i / RATE) * loudness / 127 * edge
            at += count
    return [s * 0.45 for s in out]


def write_wav(path, samples):
    with wave.open(path, 'wb') as f:
        f.setnchannels(1)
        f.setsampwidth(2)
        f.setframerate(RATE)
        f.writeframes(b''.join(struct.pack('<h', int(max(-1, min(1, s)) * 32000))
                               for s in samples))


def silence(ms):
    return [0.0] * (ms * RATE // 1000)


def main():
    write_header()
    named = dict(SOUNDS)
    for name, tracks in SOUNDS:
        ms = max(sum(note[2] for note in notes) for notes in tracks)
        print('%-14s %5d ms' % (name, ms))
    if len(sys.argv) < 2:
        return
    folder = sys.argv[1]
    os.makedirs(folder, exist_ok=True)
    for name, tracks in SOUNDS:
        write_wav(os.path.join(folder, name.lower() + '.wav'), synth(tracks))
    for name, notes in CALLS:
        write_wav(os.path.join(folder, 'call_' + name.lower() + '.wav'), synth([notes]))
    demo = synth(named['SFX_OPEN']) + silence(250)
    for plate in (0, 1, 2):
        demo += synth(step(plate)) + silence(450)
    demo += silence(500) + synth(named['SFX_PIP_1']) + silence(950)
    demo += synth(named['SFX_PIP_2']) + silence(950)
    demo += synth(named['SFX_TRANSFORM']) + silence(320)
    demo += synth([CALLS[2][1]]) + silence(3400) + synth(named['SFX_CLOSE'])
    write_wav(os.path.join(folder, 'demo.wav'), demo)


if __name__ == '__main__':
    main()
